import java.util.*;

class Solution {
    public long solution(int n) {
        long answer = 0;
        long[] dp = new long[n+1];
        dp[0] = 0;
        dp[1] = 1;
        if (n>1) dp[2] = 2;
        if (n>2) dp[3] = 3;
        if (n>3) dp[4] = 5;
        
        for (int i=5; i<=n; i++) {
            dp[i] = ((dp[i-1]%1234567)+(dp[i-2]%1234567))%1234567;
        }
        return dp[n];
    }
}
